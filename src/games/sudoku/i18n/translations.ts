export function t(
  lang: Language,
  key: string,
  params?: Record<string, string | number>,
): string {
  let value = translations[lang][key] ?? translations.ru[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      value = value.replace(`{${k}}`, String(v));
    }
  }
  return value;
}

