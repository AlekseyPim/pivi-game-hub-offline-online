/**
 * The praise line at a given index (wrapped into range), with the name filled in.
 * Deterministic: feeding the same `seed` on every device — as online play does —
 * guarantees all players read the exact same line for a move.
 */
export function praiseAt(
  lang: Language,
  kind: PraiseKind,
  name: string,
  seed: number,
): string {
  const list = (phrases[lang] ?? phrases.en!)[kind];
  const i = ((Math.floor(seed) % list.length) + list.length) % list.length;
  return list[i].replace('{name}', name);
}

/** A random praise line for the given action, with the player's name filled in. */
export function randomPraise(
  lang: Language,
  kind: PraiseKind,
  name: string,
): string {
  const list = (phrases[lang] ?? phrases.en!)[kind];
  return praiseAt(lang, kind, name, Math.floor(Math.random() * list.length));
}
